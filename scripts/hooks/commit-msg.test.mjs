import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

test("commit message checks reject AI attribution while preserving human trailers and tool descriptions", () => {
  const dir = mkdtempSync(path.join(os.tmpdir(), "commit-msg-"));
  const messageFile = path.join(dir, "message with spaces");
  const script = fileURLToPath(new URL("./commit-msg.mjs", import.meta.url));
  try {
    const blocked = [
      "Co-Authored-By: Claude <noreply@anthropic.com>",
      "co-authored-by: Codex <codex@users.noreply.github.com>",
      "Signed-off-by: Assistant <noreply@openai.com>",
      "Co-Authored-By: GitHub Copilot <copilot@github.com>",
      "Co-Authored-By: Gemini <gemini@example.com>",
      "🤖 Generated with [Claude Code](https://claude.ai/code)",
      "Generated by Codex",
      "Generated with [GitHub Copilot](https://github.com/features/copilot)",
    ];
    for (const line of blocked) {
      const message = `fix: report an error\r\n\r\n${line}\r\n`;
      writeFileSync(messageFile, message);
      const result = spawnSync(process.execPath, [script, messageFile], { encoding: "utf8" });
      assert.equal(result.status, 1, line);
      assert.match(result.stderr, /commit-msg: AI attribution is not allowed/);
      assert.equal(readFileSync(messageFile, "utf8"), message);
    }
    for (const message of [
      "feat(claude): improve the Codex and Claude settings\n",
      "fix: report an error\n\nCo-Authored-By: Junjie Bai <bjj19851010@gmail.com>\n",
      "fix: report an error\n\nCo-Authored-By: Claude Dupont <claude.dupont@example.com>\n",
      "fix: report an error\n\nSigned-off-by: Jane Doe <jane@openai.com>\n",
      "build: update dependencies\n\nSigned-off-by: dependabot[bot] <support@github.com>\n",
      "docs: explain code generation\n\nGenerated by the documentation tool.\n",
    ]) {
      writeFileSync(messageFile, message);
      const result = spawnSync(process.execPath, [script, messageFile], { encoding: "utf8" });
      assert.equal(result.status, 0, result.stderr);
    }
    const missing = spawnSync(process.execPath, [script, path.join(dir, "missing")], { encoding: "utf8" });
    assert.equal(missing.status, 1);
    assert.match(missing.stderr, /commit-msg:.*ENOENT/);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("installed commit-msg hook blocks a real commit and amend, including from a linked worktree", () => {
  const root = mkdtempSync(path.join(os.tmpdir(), "commit-msg-git-"));
  const git = (...args) => spawnSync("git", ["-c", "user.name=Test", "-c", "user.email=test@example.com", ...args], { cwd: root, encoding: "utf8" });
  try {
    assert.equal(git("init", "-q", "-b", "main").status, 0);
    mkdirSync(path.join(root, ".githooks"));
    for (const name of ["install.sh", "hook.sh"]) {
      copyFileSync(new URL(`../../.githooks/${name}`, import.meta.url), path.join(root, ".githooks", name));
    }
    mkdirSync(path.join(root, "scripts/hooks"), { recursive: true });
    copyFileSync(new URL("./commit-msg.mjs", import.meta.url), path.join(root, "scripts/hooks/commit-msg.mjs"));
    assert.equal(spawnSync("sh", [".githooks/install.sh"], { cwd: root, encoding: "utf8" }).status, 0);
    assert.equal(git("add", ".").status, 0);
    const before = git("rev-parse", "--verify", "HEAD").status;
    const blocked = git("commit", "-qm", "fix: error\n\nCo-Authored-By: Claude <noreply@anthropic.com>");
    assert.equal(blocked.status, 1);
    assert.match(blocked.stderr, /commit-msg: AI attribution is not allowed/);
    assert.equal(git("rev-parse", "--verify", "HEAD").status, before);
    assert.equal(git("commit", "-qm", "fix: error").status, 0);
    const head = git("rev-parse", "HEAD").stdout;
    const amend = git("commit", "--amend", "-qm", "fix: error\n\nGenerated with Codex");
    assert.equal(amend.status, 1);
    assert.match(amend.stderr, /commit-msg: AI attribution is not allowed/);
    assert.equal(git("rev-parse", "HEAD").stdout, head);
    const linked = path.join(root, "linked");
    assert.equal(git("worktree", "add", "--detach", linked).status, 0);
    const result = spawnSync("git", ["-c", "user.name=Test", "-c", "user.email=test@example.com", "commit", "--allow-empty", "-qm", "fix: linked\n\nCo-Authored-By: Codex <noreply@openai.com>"], { cwd: linked, encoding: "utf8" });
    assert.equal(result.status, 1);
    assert.match(result.stderr, /commit-msg: AI attribution is not allowed/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
