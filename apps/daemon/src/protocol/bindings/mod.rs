//! The contract test: the wire types rendered as TypeScript, with the protocol generation as
//! `PROTOCOL_GENERATION`, and compared with the committed `packages/ui/src/protocol.generated.ts`,
//! which the UI reads its wire types from (through `packages/ui/src/protocol.ts`).
//!
//! The wire types derive `TS` under `cfg(test)`, so the release binary carries nothing of it. A
//! field of a type the daemon only reads is `?:` where `serde` lets it be left out (an `Option`,
//! or one with a default). A plain `Option` field is `?:` with no `null`, though `serde` reads a
//! `null` as left out; a field a client does send as `null`, meaning the same as leaving it out,
//! says so with `#[ts(optional = nullable)]`, which makes it `?: T | null`. A field with a default
//! that is not an `Option` (a `bool`, a `Vec`, a `PerAgent`) refuses a `null`, so it carries none.
//! A `Present` field (`present_option`) tells a left-out key from a `null`, which clears the
//! setting, so its `| null` is part of the protocol. A field the daemon writes is optional only
//! where it skips it (`skip_serializing_if`). Where the Rust type says less than the protocol, or
//! a client's type is more exact, the field names its TypeScript type with `#[ts(type = "...")]`.
//! `ts-rs` takes `#[ts(optional)]` only on an `Option`; on anything else
//! `#[ts(optional = nullable)]` makes the field `?:` and adds no `null`.
//!
//! The same types derive `JsonSchema` for the schema contract (`schema.rs`), which follows these
//! rules but cannot read the `ts` attributes: a field that may be left out and also be `null`, or
//! one whose `#[ts(type = ...)]` narrows its type, says so to the schema with an attribute of its
//! own beside the `ts` one.
//!
//! A string enum is declared closed, the set of values the client knows and sends, and every type
//! the daemon sends names it open, as `Received<Enum>` (`T | (string & {})`), since output enums
//! may gain values within a generation: a `switch` that must cover every value, or a lookup by a
//! received value in a `Record<Enum, …>`, then fails to type-check instead of breaking on a new
//! value. A field narrowed to a union of string literals with `#[ts(type = ...)]` is opened the
//! same way. A type both sides send is a type the daemon sends. The discriminant of a tagged union
//! (`"type": "hello"`, a `kind`) is a single literal and stays closed: opened, it would no longer
//! narrow the union, so a client handles a variant it does not know by hand (`received.rs`).
//!
//! A wire type's doc comment is copied into the rendering as it is, so it links only in forms that
//! still read as prose there: a rustdoc link-definition line (`[`X`]: path`) would show up in the
//! TypeScript as a stray line.

