//! The contract test: the wire types rendered as TypeScript and compared with the committed
//! `packages/ui/src/protocol.generated.ts`, which the UI's own types are checked against
//! (`packages/ui/src/protocol.contract.ts`).
//!
//! The wire types derive `TS` under `cfg(test)`, so the release binary carries nothing of it. A
//! field of a type the daemon only reads is `?:` where `serde` lets it be left out (an `Option`,
//! or one with a default). A plain `Option` field is `?:` with no `null`, though `serde` reads a
//! `null` as left out; a field a client does send as `null`, meaning the same as leaving it out,
//! says so with `#[ts(optional = nullable)]`, which makes it `?: T | null`. A field with a default
//! that is not an `Option` (a `bool`, a `Vec`, a `PerAgent`) refuses a `null`, so it carries none.
//! A `Present` field (`present_option`) tells a left-out key from a `null`, which clears the
//! setting, so its `| null` is part of the protocol. A field the daemon writes is optional only
//! where it skips it (`skip_serializing_if`). Where the Rust type says less than the protocol, or
//! a client's type is more exact, the field names its TypeScript type with `#[ts(type = "...")]`.
//! `ts-rs` takes `#[ts(optional)]` only on an `Option`; on anything else
//! `#[ts(optional = nullable)]` makes the field `?:` and adds no `null`.

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};
use std::path::PathBuf;

use ts_rs::{Config, TypeVisitor, TS};

use super::{
    BrowseRequest, Change, Code, Event, PerAgent, Request, RequestBody, TermControl, TermEvent,
};

/// Where the rendering is committed, and the variable that makes the test write it instead of
/// comparing with it. `pnpm verify` is read-only, so it never sets it.
const OUTPUT: &str = "../../packages/ui/src/protocol.generated.ts";
const WRITE_VARIABLE: &str = "OCTOBOARD_WRITE_BINDINGS";

const HEADER: &str = "\
// Generated by `OCTOBOARD_WRITE_BINDINGS=1 cargo test -p octoboardd bindings`; do not edit.
// The wire types of `apps/daemon/src/protocol.rs` and the modules it names, as the daemon
// serialises and reads them. `protocol.contract.ts` checks the hand-written `protocol.ts`
// against this file.
";

/// A code is a plain string on the wire; its type exists to keep codes in one place in Rust.
impl TS for Code {
    type WithoutGenerics = Self;
    type OptionInnerType = Self;

    fn name(_: &Config) -> String {
        "string".to_string()
    }

    fn inline(cfg: &Config) -> String {
        Self::name(cfg)
    }
}

/// An update's value for one setting: the key left out, `null`, or a value. The key being left out
/// is the field's own optionality, so the value reads as nullable.
impl<T: TS + 'static> TS for Change<T> {
    type WithoutGenerics = Self;
    type OptionInnerType = Self;

    fn name(cfg: &Config) -> String {
        format!("{} | null", T::name(cfg))
    }

    fn inline(cfg: &Config) -> String {
        Self::name(cfg)
    }

    fn visit_generics(visitor: &mut impl TypeVisitor) {
        visitor.visit::<T>();
    }
}

/// A model and effort in a create request, where either may be left out; `Launch` is the record,
/// which always carries both.
pub struct LaunchRequest;

impl TS for LaunchRequest {
    type WithoutGenerics = Self;
    type OptionInnerType = Self;

    fn name(_: &Config) -> String {
        "{ model?: string, effort?: string }".to_string()
    }

    fn inline(cfg: &Config) -> String {
        Self::name(cfg)
    }
}

/// A request's per-agent value: an agent may be left out, so the agents' record is partial.
/// Named by `#[ts(as = ...)]` on the request fields that read a `PerAgent`.
pub struct PartialPerAgent<T>(std::marker::PhantomData<T>);

impl<T: TS + 'static> TS for PartialPerAgent<T> {
    type WithoutGenerics = Self;
    type OptionInnerType = Self;

    fn name(cfg: &Config) -> String {
        format!("Partial<{}>", PerAgent::<T>::name(cfg))
    }

    fn inline(cfg: &Config) -> String {
        Self::name(cfg)
    }

    fn visit_generics(visitor: &mut impl TypeVisitor) {
        visitor.visit::<PerAgent<T>>();
    }
}

/// Collects the declaration of every type reachable from the roots, named types only: a `Vec`,
/// an `Option` or a primitive has no declaration of its own and is looked through.
struct Collector<'a> {
    cfg: &'a Config,
    seen: HashSet<TypeId>,
    declarations: BTreeMap<String, String>,
}

impl TypeVisitor for Collector<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if T::output_path().is_some() {
            if !self.seen.insert(TypeId::of::<T>()) {
                return;
            }
            // A generic type is declared once, in its generic form, whatever it is used with.
            let name = T::ident(self.cfg);
            self.declarations.entry(name).or_insert_with(|| {
                let docs = T::docs().unwrap_or_default();
                format!("{docs}export {}\n", pretty(&T::decl(self.cfg)))
            });
            T::visit_dependencies(self);
        }
        // A type with no declaration of its own is reached through what it wraps, which its
        // generics name; its dependencies are the wrapped type's, visited on their own.
        T::visit_generics(self);
    }
}

/// Lays a declaration out one field and one union member to a line. `ts-rs` writes each on a
/// single line, which would make a change to one field a change to a line of many kilobytes. Only
/// whitespace is added or dropped, outside the doc comments, which are kept as they are.
fn pretty(declaration: &str) -> String {
    const INDENT: &str = "  ";
    let mut out = String::new();
    // What each open bracket is, so that a comma or a bar breaks a line only between the fields of
    // an object or the members of a union, not between generic arguments.
    let mut open: Vec<char> = Vec::new();
    let mut chars = declaration.chars().peekable();
    let newline = |out: &mut String, depth: usize| {
        while out.ends_with(' ') {
            out.pop();
        }
        if !out.is_empty() && !out.ends_with('\n') {
            out.push('\n');
        }
        out.push_str(&INDENT.repeat(depth));
    };
    let depth = |open: &[char]| open.iter().filter(|bracket| **bracket == '{').count();
    while let Some(c) = chars.next() {
        match c {
            '"' => {
                out.push(c);
                for inner in chars.by_ref() {
                    out.push(inner);
                    if inner == '"' {
                        break;
                    }
                }
            }
            '/' if chars.peek() == Some(&'*') => {
                let mut comment = String::from('/');
                let mut previous = c;
                for inner in chars.by_ref() {
                    comment.push(inner);
                    if previous == '*' && inner == '/' {
                        break;
                    }
                    previous = inner;
                }
                let indent = INDENT.repeat(depth(&open));
                newline(&mut out, depth(&open));
                for (n, line) in comment.lines().enumerate() {
                    if n > 0 {
                        out.push('\n');
                        out.push_str(&indent);
                        if line.trim_start().starts_with('*') {
                            out.push(' ');
                        }
                    }
                    out.push_str(if n == 0 { line } else { line.trim_start() });
                }
                newline(&mut out, depth(&open));
            }
            '{' => {
                open.push('{');
                while chars.peek() == Some(&' ') {
                    chars.next();
                }
                if chars.peek() == Some(&'}') {
                    chars.next();
                    open.pop();
                    out.push_str("{}");
                } else {
                    out.push('{');
                    newline(&mut out, depth(&open));
                }
            }
            '}' => {
                open.pop();
                newline(&mut out, depth(&open));
                out.push('}');
            }
            '<' | '(' | '[' => {
                open.push(c);
                out.push(c);
            }
            '>' | ')' | ']' => {
                open.pop();
                out.push(c);
            }
            ',' if open.last() == Some(&'{') => {
                out.push(',');
                while chars.peek() == Some(&' ') {
                    chars.next();
                }
                if chars.peek() != Some(&'}') {
                    newline(&mut out, depth(&open));
                }
            }
            '|' if out.trim_end().ends_with('}') && open.iter().all(|bracket| *bracket == '(') => {
                newline(&mut out, depth(&open) + open.len());
                out.push_str("| ");
                while chars.peek() == Some(&' ') {
                    chars.next();
                }
            }
            ' ' | '\n' => {
                // Spaces lead nothing and follow nothing but one; a source line break is a space.
                let leading = out.trim_end_matches(' ').ends_with('\n') || out.is_empty();
                if !leading && !out.ends_with(' ') {
                    out.push(' ');
                }
            }
            _ => out.push(c),
        }
    }
    out
}

fn render() -> String {
    let cfg = Config::new().with_large_int("number");
    let mut collector = Collector {
        cfg: &cfg,
        seen: HashSet::new(),
        declarations: BTreeMap::new(),
    };
    // Everything else is reached from these roots through ts-rs's dependency walk, which does not
    // follow a type named only by `#[ts(as = ...)]` or `#[ts(type = ...)]`: such a type has to be
    // reachable another way, or its declaration is silently left out.
    collector.visit::<Event>();
    collector.visit::<Request>();
    collector.visit::<BrowseRequest>();
    collector.visit::<RequestBody>();
    collector.visit::<TermControl>();
    collector.visit::<TermEvent>();
    let mut out = HEADER.to_string();
    for declaration in collector.declarations.values() {
        out.push('\n');
        out.push_str(declaration);
    }
    out
}

#[test]
fn committed_bindings_are_current() {
    let rendered = render();
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(OUTPUT);
    if std::env::var_os(WRITE_VARIABLE).is_some_and(|value| value == "1") {
        std::fs::write(&path, &rendered).unwrap();
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    if committed != rendered {
        panic!(
            "packages/ui/src/protocol.generated.ts is out of date with the wire types; regenerate \
             it with `{WRITE_VARIABLE}=1 cargo test -p octoboardd bindings` and commit it.\n{}",
            line_diff(&committed, &rendered)
        );
    }
}

/// The lines only one side has, `-` for the committed file and `+` for the rendering, capped so
/// a wholesale change stays readable.
fn line_diff(committed: &str, rendered: &str) -> String {
    const LIMIT: usize = 40;
    let committed_lines: HashSet<&str> = committed.lines().collect();
    let rendered_lines: HashSet<&str> = rendered.lines().collect();
    let removed = committed
        .lines()
        .filter(|line| !rendered_lines.contains(line));
    let added = rendered
        .lines()
        .filter(|line| !committed_lines.contains(line));
    let mut lines: Vec<String> = removed
        .map(|line| format!("- {line}"))
        .chain(added.map(|line| format!("+ {line}")))
        .collect();
    let more = lines.len().saturating_sub(LIMIT);
    lines.truncate(LIMIT);
    if more > 0 {
        lines.push(format!("… and {more} more differing lines"));
    }
    lines.join("\n")
}

#[test]
fn a_declaration_is_laid_out_by_field_and_by_union_member_and_nothing_else_changes() {
    let declaration = "type A = { \"type\": \"x, y\", a: Record<string, B | null>, \n/**\n * Says what b is.\n */\nb?: Array<{ c: number, }>, d: {  }, } | { e: [string, number], };";
    let expected = "\
type A = {
  \"type\": \"x, y\",
  a: Record<string, B | null>,
  /**
   * Says what b is.
   */
  b?: Array<{
    c: number,
  }>,
  d: {},
}
| {
  e: [string, number],
};";
    let laid_out = pretty(declaration);
    assert_eq!(laid_out, expected);
    let bare = |text: &str| text.split_whitespace().collect::<String>();
    assert_eq!(bare(&laid_out), bare(declaration));
}
